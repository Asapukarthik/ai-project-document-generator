settings = get_settings()

# Corporate Palette Tokens
COLOR_PRIMARY_NAVY = RGBColor(27, 54, 93)     # #1B365D
COLOR_SECONDARY_SLATE = RGBColor(74, 85, 104) # #4A5568
COLOR_CHARCOAL = RGBColor(45, 55, 72)         # #2D3748
COLOR_MUTED_GRAY = RGBColor(113, 128, 150)    # #718096
HEX_NAVY_BG = "1B365D"
HEX_LIGHT_GRAY_BG = "F7FAFC"
HEX_BORDER_GRAY = "E2E8F0"
HEX_WARNING_BG = "FFF5F5"
HEX_WARNING_BORDER = "FEB2B2"


def set_cell_background(cell, hex_color: str) -> None:
    """Sets background color of a table cell."""
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{hex_color}"/>')
    tc_pr.append(shd)


def set_cell_margins(cell, top=100, bottom=100, left=150, right=150) -> None:
    """Sets inner padding for a table cell in twips."""
    tc_pr = cell._tc.get_or_add_tcPr()
    tc_mar = parse_xml(
        f'<w:tcMar {nsdecls("w")}>'
        f'<w:top w:w="{top}" w:type="dxa"/>'
        f'<w:bottom w:w="{bottom}" w:type="dxa"/>'
        f'<w:left w:w="{left}" w:type="dxa"/>'
        f'<w:right w:w="{right}" w:type="dxa"/>'
        f'</w:tcMar>'
    )
    tc_pr.append(tc_mar)


class DocxGenerator:
    """
    Generates professional, enterprise-grade Microsoft Word (.docx) documents
    from validated ProjectDocument schemas.
    """

    def __init__(self, project_doc: ProjectDocument):
        self.doc_data = project_doc
        self.document = Document()
        self._configure_document_styles()

    def _configure_document_styles(self) -> None:
        """Sets default page geometry, typography, and margins."""
        # 1-inch margins
        for section in self.document.sections:
            section.top_margin = Inches(1.0)
            section.bottom_margin = Inches(1.0)
            section.left_margin = Inches(1.0)
            section.right_margin = Inches(1.0)

            # Configure Header & Footer
            header = section.header
            header_p = header.paragraphs[0]
            header_p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            run_h = header_p.add_run(f"Project Specification | {self.doc_data.project_title[:45]}")
            run_h.font.name = "Calibri"
            run_h.font.size = Pt(8.5)
            run_h.font.color.rgb = COLOR_MUTED_GRAY

            footer = section.footer
            footer_p = footer.paragraphs[0]
            footer_p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            run_f = footer_p.add_run("Confidential - Generated by AI-Powered Project Documentation Generator")
            run_f.font.name = "Calibri"
            run_f.font.size = Pt(8.5)
            run_f.font.color.rgb = COLOR_MUTED_GRAY

        # Configure Base Styles
        styles = self.document.styles

        # Normal text style
        normal_style = styles["Normal"]
        normal_font = normal_style.font
        normal_font.name = "Calibri"
        normal_font.size = Pt(11)
        normal_font.color.rgb = COLOR_CHARCOAL
        normal_style.paragraph_format.line_spacing = 1.2
        normal_style.paragraph_format.space_after = Pt(6)

    def _add_cover_page(self) -> None:
        """Builds a formal corporate cover page."""
        # Vertical spacing
        for _ in range(3):
            self.document.add_paragraph()

        # Document Type Label
        p_label = self.document.add_paragraph()
        run_label = p_label.add_run("PROJECT SPECIFICATION & TERMS OF REFERENCE")
        run_label.font.name = "Calibri"
        run_label.font.size = Pt(12)
        run_label.font.bold = True
        run_label.font.color.rgb = COLOR_SECONDARY_SLATE

        # Main Title
        p_title = self.document.add_paragraph()
        run_title = p_title.add_run(self.doc_data.project_title)
        run_title.font.name = "Calibri"
        run_title.font.size = Pt(26)
        run_title.font.bold = True
        run_title.font.color.rgb = COLOR_PRIMARY_NAVY
        p_title.paragraph_format.space_after = Pt(18)

        # Decorative Horizontal Rule Table
        rule_table = self.document.add_table(rows=1, cols=1)
        rule_table.alignment = WD_TABLE_ALIGNMENT.LEFT
        rule_cell = rule_table.cell(0, 0)
        set_cell_background(rule_cell, HEX_NAVY_BG)
        rule_cell.width = Inches(6.5)
        rule_table.rows[0].height = Pt(3)

        self.document.add_paragraph()  # Spacing

        # Metadata Box
        meta_table = self.document.add_table(rows=3, cols=2)
        meta_table.alignment = WD_TABLE_ALIGNMENT.LEFT
        meta_rows = [
            ("Document Type:", "Project Requirement Document (PRD / ToR)"),
            ("Generation Date:", datetime.now(timezone.utc).strftime("%B %d, %Y")),
            ("Provenance Status:", "Extracted via Local LLM with Zero Hallucination Guardrails")
        ]
        for idx, (label, val) in enumerate(meta_rows):
            cell_lbl = meta_table.cell(idx, 0)
            cell_val = meta_table.cell(idx, 1)
            cell_lbl.width = Inches(2.0)
            cell_val.width = Inches(4.5)

            r_lbl = cell_lbl.paragraphs[0].add_run(label)
            r_lbl.font.bold = True
            r_lbl.font.size = Pt(10)
            r_lbl.font.color.rgb = COLOR_SECONDARY_SLATE

            r_val = cell_val.paragraphs[0].add_run(val)
            r_val.font.size = Pt(10)
            r_val.font.color.rgb = COLOR_CHARCOAL

        # Page break after cover page
        self.document.add_page_break()

    def _add_heading(self, text: str, level: int = 1) -> None:
        """Adds a consistently styled heading."""
        p = self.document.add_paragraph()
        run = p.add_run(text)
        run.font.name = "Calibri"
        run.font.bold = True

        if level == 1:
            run.font.size = Pt(16)
            run.font.color.rgb = COLOR_PRIMARY_NAVY
            p.paragraph_format.space_before = Pt(16)
            p.paragraph_format.space_after = Pt(8)
        elif level == 2:
            run.font.size = Pt(13)
            run.font.color.rgb = COLOR_SECONDARY_SLATE
            p.paragraph_format.space_before = Pt(12)
            p.paragraph_format.space_after = Pt(4)

    def _build_sections(self) -> None:
        """Constructs all required document sections."""
        # 1. Project Title & Executive Overview
        self._add_heading("1. Project Title & Overview", level=1)
        p_title = self.document.add_paragraph()
        r = p_title.add_run(f"Project Title: {self.doc_data.project_title}\n")
        r.font.bold = True

        # 2. Scope of Work
        self._add_heading("2. Scope of Work", level=1)
        p_scope = self.document.add_paragraph(self.doc_data.scope_of_work)
        p_scope.paragraph_format.line_spacing = 1.25

        # 3. Objectives
        self._add_heading("3. Project Objectives", level=1)
        for obj in self.doc_data.objectives:
            p = self.document.add_paragraph(style="List Bullet")
            p.add_run(obj)

        # 4. Methodology
        self._add_heading("4. Project Methodology & Execution Framework", level=1)
        for step in self.doc_data.methodology:
            p_step = self.document.add_paragraph()
            r_num = p_step.add_run(f"Step {step.step_number}: {step.title}\n")
            r_num.font.bold = True
            r_num.font.color.rgb = COLOR_PRIMARY_NAVY

            r_desc = p_step.add_run(step.description)
            if step.source_page and step.source_page != "Not specified in the source document":
                p_cite = self.document.add_paragraph()
                r_cite = p_cite.add_run(f"[Source: {step.source_page}]")
                r_cite.font.italic = True
                r_cite.font.size = Pt(9.5)
                r_cite.font.color.rgb = COLOR_MUTED_GRAY

        # 5. Project Timeline Table
        self._add_heading("5. Project Timeline & Milestone Schedule", level=1)
        timeline_items = self.doc_data.project_timeline
        table = self.document.add_table(rows=1 + len(timeline_items), cols=5)
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        table.autofit = False

        headers = ["Milestone", "Deliverables / Description", "Start Date", "End Date", "Duration"]
        col_widths = [Inches(1.5), Inches(2.2), Inches(0.9), Inches(0.9), Inches(1.0)]

        # Header Row
        hdr_row = table.rows[0]
        for idx, text in enumerate(headers):
            cell = hdr_row.cells[idx]
            cell.width = col_widths[idx]
            set_cell_background(cell, HEX_NAVY_BG)
            set_cell_margins(cell, top=120, bottom=120, left=120, right=120)
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = p.add_run(text)
            run.font.bold = True
            run.font.size = Pt(9.5)
            run.font.color.rgb = RGBColor(255, 255, 255)

        # Data Rows
        for r_idx, item in enumerate(timeline_items, start=1):
            row = table.rows[r_idx]
            row_data = [
                item.milestone,
                item.description,
                item.start_date or "-",
                item.end_date or "-",
                item.duration or "-"
            ]
            bg_color = HEX_LIGHT_GRAY_BG if r_idx % 2 == 0 else "FFFFFF"

            for c_idx, val in enumerate(row_data):
                cell = row.cells[c_idx]
                cell.width = col_widths[c_idx]
                set_cell_background(cell, bg_color)
                set_cell_margins(cell, top=80, bottom=80, left=100, right=100)
                p = cell.paragraphs[0]
                if c_idx in [2, 3, 4]:
                    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                run = p.add_run(val)
                run.font.size = Pt(9.5)

        self.document.add_paragraph()  # spacing

        # 6. Source References & Grounding Audit
        self._add_heading("6. Source References & Document Provenance", level=1)
        if self.doc_data.source_references:
            for ref in self.doc_data.source_references:
                p_ref = self.document.add_paragraph(style="List Bullet")
                p_ref.add_run(ref)
        else:
            self.document.add_paragraph("No explicit page citations were recorded during extraction.")

        # 7. Missing Information & Project Gaps
        self._add_heading("7. Missing Information & Project Gaps", level=1)
        if self.doc_data.missing_information:
            warn_table = self.document.add_table(rows=len(self.doc_data.missing_information), cols=1)
            warn_table.alignment = WD_TABLE_ALIGNMENT.LEFT
            for idx, missing in enumerate(self.doc_data.missing_information):
                cell = warn_table.cell(idx, 0)
                set_cell_background(cell, HEX_WARNING_BG)
                set_cell_margins(cell, top=100, bottom=100, left=150, right=150)
                p = cell.paragraphs[0]
                r_icon = p.add_run("⚠ Notice: ")
                r_icon.font.bold = True
                r_icon.font.color.rgb = RGBColor(197, 48, 48)
                r_text = p.add_run(missing)
                r_text.font.size = Pt(10)
        else:
            self.document.add_paragraph("All standard project dimensions were identified in the source document.")

        # 8. Human Review & Stakeholder Sign-Off Notes
        self._add_heading("8. Stakeholder Review & Sign-Off", level=1)
        p_sign = self.document.add_paragraph(
            "This document was synthesized from original project specifications and reviewed prior to authorization. "
            "Any discrepancies or required amendments should be noted below before milestone kickoff."
        )
        p_sign.paragraph_format.space_after = Pt(18)

        # Signature Table
        sign_table = self.document.add_table(rows=2, cols=3)
        sign_table.alignment = WD_TABLE_ALIGNMENT.CENTER
        labels = ["Reviewer Name & Title", "Signature", "Date"]
        for c_idx, label in enumerate(labels):
            cell_top = sign_table.cell(0, c_idx)
            cell_bottom = sign_table.cell(1, c_idx)
            cell_top.width = Inches(2.1)
            cell_bottom.width = Inches(2.1)
            p_top = cell_top.paragraphs[0]
            p_top.add_run(f"\n_______________________\n{label}").font.size = Pt(9.5)

    def generate(self, output_path: Path) -> Path:
        """
        Builds and saves the complete Word document to the designated output path.
        """
        self._add_cover_page()
        self._build_sections()
        output_path.parent.mkdir(parents=True, exist_ok=True)
        self.document.save(str(output_path))
        return output_path
